import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { AnimationMixer, LoopOnce, Quaternion } from 'three'
import { FBXLoader } from 'three/addons/loaders/FBXLoader.js'

// Bake local FEZ joint rotations. The downloaded Adobe rig and FBX stay out of the game.
const input = process.argv[2]
if (!input) throw Error('Usage: node artwork/characters/bake-athena-kiss.mjs "Blow A Kiss.fbx"')
const bytes = await readFile(input)
const sha256 = createHash('sha256').update(bytes).digest('hex')
const fbx = new FBXLoader().parse(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength),'')
const clip = fbx.animations[0]
if (!clip || !clip.duration) throw Error('The source contains no animation')
const source = new Map()
fbx.traverse(node => { if (node.isBone) source.set(node.name.replace(/^.*?mixamorig\d*[:_]?/i,''),node) })
const mapping = [['spine','Spine'],['chest','Spine2'],['neck','Neck'],['head','Head']]
for (const [side,suffix] of [['Left','L'],['Right','R']]) {
  for (const [name,original] of [['shoulder','Shoulder'],['upper_arm','Arm'],['lower_arm','ForeArm'],['hand','Hand']]) {
    mapping.push([name+'_'+suffix,side+original])
  }
  for (const [finger,original] of [['thumb','Thumb'],['index','Index'],['middle','Middle'],['ring','Ring'],['little','Pinky']]) {
    for (const [i,segment] of ['proximal','intermediate','distal'].entries()) {
      mapping.push([finger+'_'+segment+'_'+suffix,side+'Hand'+original+(i+1)])
    }
  }
}

const targetBytes = await readFile(new URL('../../public/character/athena-seat.glb',import.meta.url))
const doc = JSON.parse(targetBytes.toString('utf8',20,20+targetBytes.readUInt32LE(12)))
const byName = new Map(doc.nodes.map((node,i)=>[node.name,i]))
const parent = new Map()
doc.nodes.forEach((node,i)=>node.children?.forEach(child=>parent.set(child,i)))
const bind = i => {
  const q = new Quaternion().fromArray(doc.nodes[i].rotation ?? [0,0,0,1])
  return parent.has(i) ? bind(parent.get(i)).multiply(q) : q
}
fbx.updateMatrixWorld(true)
const joints = mapping.map(([name,original])=>{
  const bone=source.get(original),id=byName.get(name)
  if (!bone || id===undefined) throw Error('Missing joint '+name+' / '+original)
  return {name,bone,id,bind:bind(id),sourceInv:bone.getWorldQuaternion(new Quaternion()).invert(),previous:new Quaternion()}
})
const mixer=new AnimationMixer(fbx), action=mixer.clipAction(clip).setLoop(LoopOnce,1)
action.clampWhenFinished=true
action.play()
const frameCount=Math.round(clip.duration*30)+1
const packed=Buffer.alloc(frameCount*joints.length*8)
const inverseParent=new Quaternion(), q=new Quaternion()
const posed=new Map()
for(let f=0;f<frameCount;f++){
  mixer.setTime(f*clip.duration/(frameCount-1))
  fbx.updateMatrixWorld(true)
  for(const [column,j] of joints.entries()){
    // Preserve the original world-space motion relative to the source bind pose,
    // then re-express it in Athena's local bind axes. Her extra spine joint is collapsed.
    const world=j.bone.getWorldQuaternion(new Quaternion()).multiply(j.sourceInv).multiply(j.bind)
    posed.set(j.id,world)
    inverseParent.copy(posed.get(parent.get(j.id)) ?? bind(parent.get(j.id))).invert()
    q.copy(inverseParent).multiply(world).normalize()
    if(f && j.previous.dot(q)<0)q.set(-q.x,-q.y,-q.z,-q.w)
    j.previous.copy(q)
    q.toArray().forEach((component,i)=>packed.writeInt16LE(Math.round(component*32767),((f*joints.length+column)*4+i)*2))
  }
}
const data={source:'Adobe Mixamo / Blow A Kiss',sourceSha256:sha256,frames:frameCount,duration:clip.duration,
  joints:joints.map(j=>j.name),rotations:packed.toString('base64')}
await writeFile(new URL('../../src/athena-kiss-data.ts',import.meta.url),
  '// Generated by artwork/characters/bake-athena-kiss.mjs from the animation-only Y Bot download.\nexport default '+JSON.stringify(data)+'\n')
console.log(sha256,frameCount+' frames',joints.length+' FEZ joints',clip.duration+' seconds')
